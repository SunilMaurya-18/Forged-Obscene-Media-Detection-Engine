import pytest
from fastapi.testclient import TestClient
from PIL import Image

import content_credentials as cc
import provenance

pytestmark = pytest.mark.skipif(not cc.AVAILABLE, reason="c2pa-python not installed")

CHECKPOINT = Path(
    os.getenv("FORGERY_CHECKPOINT", Path(__file__).resolve().parent.parent / "ml" / "models" / "checkpoint.pt")
)
AI_SOURCE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"


def _image(fmt: str = "JPEG", size: int = 96) -> bytes:
    img = Image.new("RGB", (size, size), (70, 110, 160))
    for x in range(0, size, 3):
        img.putpixel((x, (x * 7) % size), (240, 30, 90))
    buf = io.BytesIO()
    img.save(buf, format=fmt)
    return buf.getvalue()


def c2pa_signed_sample(fmt: str = "JPEG", size: int = 96) -> bytes:
    """A synthetic image whose C2PA manifest declares it was generated by an AI model, then edited."""
    manifest = {
        "claim_generator_info": [{"name": "SyntheticStudio", "version": "2.1"}],
        "title": "synthetic-portrait.jpg",
        "assertions": [{
            "label": "c2pa.actions",
            "data": {"actions": [
                {"action": "c2pa.created", "digitalSourceType": AI_SOURCE,
                 "softwareAgent": {"name": "SyntheticStudio", "version": "2.1"}},
                {"action": "c2pa.color_adjustments", "softwareAgent": {"name": "PhotoFixer"}},
            ]},
        }],
    }
    return cc.sign_manifest(_image(fmt, size), manifest)


def test_unsigned_image_has_no_credentials():
    assert cc.read(_image("JPEG")) is None
    assert cc.read(_image("PNG")) is None
    assert cc.read(b"not an image") is None


@pytest.mark.parametrize("fmt", ["JPEG", "PNG"])
def test_reads_signer_generator_and_actions(fmt):
    summary = cc.read(c2pa_signed_sample(fmt))
    assert summary["present"] is True
    assert summary["status"] == "VALID_UNTRUSTED"  # genuine signature, dev certificate not on a trust list
    assert summary["signer"]["common_name"] == "Forged Media Detection (dev)"
    assert summary["signer"]["trusted"] is False
    assert summary["claim_generator"].startswith("SyntheticStudio 2.1")
    assert [a["action"] for a in summary["actions"]] == ["c2pa.created", "c2pa.color_adjustments"]
    assert summary["actions"][0]["software_agent"] == "SyntheticStudio 2.1"
    assert summary["ai_generated"] is True


COMMITTED_SAMPLE = Path(__file__).resolve().parent.parent / "frontend" / "public" / "c2pa-sample.jpg"


@pytest.mark.skipif(not COMMITTED_SAMPLE.exists(), reason="frontend/public not present")
def test_committed_demo_sample_still_validates():
    # Fails once the sample's dev leaf expires: regenerate with tools/make_phase23_samples.py
    summary = cc.read(COMMITTED_SAMPLE.read_bytes())
    assert summary["status"] == "VALID_UNTRUSTED", summary["failures"]
    assert summary["ai_generated"] is True


def test_pixel_edit_after_signing_is_invalid():
    signed = bytearray(c2pa_signed_sample("JPEG"))
    signed[-120] ^= 0xFF
    summary = cc.read(bytes(signed))
    assert summary["status"] == "INVALID"
    assert "assertion.dataHash.mismatch" in summary["failures"]


def test_label_keeps_xmp_and_adds_c2pa_with_upload_as_parent():
    original = c2pa_signed_sample("JPEG")
    manifest = provenance.build_manifest(original, "pid-c2pa", "2026-09-28T09:00:00Z", 0.42, 0.03, "REVIEW")
    xmp_labelled, _ = provenance.embed(original, manifest)
    labelled = cc.sign(xmp_labelled, original, {"provenance_id": "pid-c2pa", "decision": "REVIEW"})

    assert provenance.verify(labelled)["status"] == "VERIFIED"
    assert labelled.count(b"<x:xmpmeta") == 1
    with Image.open(io.BytesIO(original)) as a, Image.open(io.BytesIO(labelled)) as b:
        assert a.convert("RGB").tobytes() == b.convert("RGB").tobytes()

    summary = cc.read(labelled)
    assert summary["claim_generator"].startswith("forged-media-detection")
    assert [a["action"] for a in summary["actions"]] == ["c2pa.opened", "c2pa.published"]
    assert summary["fmd_analysis"]["provenance_id"] == "pid-c2pa"
    assert summary["ingredients"][0]["relationship"] == "parentOf"
    assert summary["ingredients"][0]["has_manifest"] is True  # the upload's own credentials are kept
    assert summary["manifest_count"] == 2


