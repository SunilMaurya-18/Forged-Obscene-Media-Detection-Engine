def test_embed_endpoint_writes_both_labels(api):
    r = api.post(
        "/provenance/embed",
        files={"file": ("a.png", _image("PNG"), "image/png")},
        data={"provenance_id": "http-c2pa", "analyzed_at": "2026-09-28T09:00:00Z",
              "forgery_score": "0.3", "explicit_score": "0.01", "decision": "ALLOW"},
    )
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["manifest"]["status"] == "VERIFIED"
    assert body["c2pa"]["status"] == "VALID_UNTRUSTED"
    assert body["c2pa_error"] is None
    labelled = base64.b64decode(body["image"])

    read = api.post("/provenance/read", files={"file": ("a.png", labelled, "image/png")}).json()
    assert read["provenance"]["provenance_id"] == "http-c2pa"
    assert read["c2pa"]["fmd_analysis"]["decision"] == "ALLOW"


def test_embed_endpoint_can_skip_c2pa(api, monkeypatch):
    monkeypatch.setenv("C2PA_WRITE", "0")
    r = api.post(
        "/provenance/embed",
        files={"file": ("a.jpg", _image("JPEG"), "image/jpeg")},
        data={"provenance_id": "xmp-only", "analyzed_at": "t", "forgery_score": "0.1", "explicit_score": "0", "decision": "ALLOW"},
    )
    assert r.json()["c2pa"] is None
    assert r.json()["manifest"]["status"] == "VERIFIED"


def test_infer_surfaces_c2pa_manifest_details():
    """DoD: a C2PA-signed sample shows its manifest details in the analysis response."""
    if not CHECKPOINT.exists():
        pytest.skip(f"Missing checkpoint: {CHECKPOINT}")
    os.environ["NSFW_BACKEND"] = "heuristic"
    import inference as inf
    import main

    if inf._runtime is None:
        inf.init_runtime(checkpoint=CHECKPOINT, device="cpu")
    api = TestClient(main.app)

    body = api.post("/infer", files={"file": ("s.jpg", c2pa_signed_sample("JPEG", 224), "image/jpeg")}).json()
    c2pa = body["c2pa"]
    assert c2pa["signer"]["common_name"] == "Forged Media Detection (dev)"
    assert c2pa["claim_generator"].startswith("SyntheticStudio")
    assert c2pa["actions"][0]["digital_source_type"] == AI_SOURCE
    assert c2pa["ai_generated"] is True

    plain = api.post("/infer", files={"file": ("p.jpg", _image("JPEG", 224), "image/jpeg")}).json()
    assert plain["c2pa"] is None
